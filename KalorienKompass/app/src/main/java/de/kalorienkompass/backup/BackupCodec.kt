package de.kalorienkompass.backup

import kotlinx.serialization.KSerializer
import kotlinx.serialization.SerializationException
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.intOrNull
import java.time.Instant
import java.time.OffsetDateTime
import java.time.format.DateTimeFormatter
import java.time.temporal.ChronoUnit

/**
 * Encodes/decodes [BackupFile]s and validates format and version.
 * Pure JVM code (unit-tested); all errors are [BackupException]s with German messages.
 */
object BackupCodec {

    const val MSG_NOT_A_BACKUP: String = "Diese Datei ist kein KalorienKompass-Backup."
    const val MSG_CORRUPT: String = "Das Backup ist beschädigt oder unvollständig und kann nicht importiert werden."

    // Explicit type: KSP (Room) cannot see serializers generated by the serialization plugin.
    private val fileSerializer: KSerializer<BackupFile> = BackupFile.serializer()

    /** Settings used for backups (also applied on top of the app's [Json] instance). */
    private val defaultJson: Json = Json {
        ignoreUnknownKeys = true
        encodeDefaults = true
        coerceInputValues = true
        isLenient = true
        allowSpecialFloatingPointValues = true
        prettyPrint = false
    }

    /** The app's [Json] with the flags a backup needs (defaults are always written, unknown keys ignored). */
    fun configure(base: Json): Json = Json(from = base) {
        ignoreUnknownKeys = true
        encodeDefaults = true
        coerceInputValues = true
        isLenient = true
        allowSpecialFloatingPointValues = true
        prettyPrint = false
    }

    fun encode(file: BackupFile, json: Json = defaultJson): String = json.encodeToString(fileSerializer, file)

    /** Parses and validates a backup; throws [BackupException] if it is not a (supported) backup. */
    fun decode(text: String, json: Json = defaultJson): BackupFile {
        val trimmed = text.removePrefix(BOM).trim()
        if (trimmed.isEmpty()) throw BackupException("Die ausgewählte Datei ist leer.")

        val element: JsonElement = try {
            json.parseToJsonElement(trimmed)
        } catch (e: SerializationException) {
            throw BackupException(MSG_NOT_A_BACKUP, e)
        } catch (e: IllegalArgumentException) {
            throw BackupException(MSG_NOT_A_BACKUP, e)
        }
        val root = element as? JsonObject ?: throw BackupException(MSG_NOT_A_BACKUP)

        val format = (root["format"] as? JsonPrimitive)?.contentOrNull
        if (format != BackupFile.FORMAT_ID) throw BackupException(MSG_NOT_A_BACKUP)

        val version = (root["version"] as? JsonPrimitive)?.intOrNull ?: throw BackupException(MSG_CORRUPT)
        if (version < 1) throw BackupException(MSG_CORRUPT)
        if (version > BackupFile.CURRENT_VERSION) {
            throw BackupException(
                "Dieses Backup stammt aus einer neueren Version von KalorienKompass (Format $version). " +
                    "Bitte aktualisiere die App und versuche es erneut.",
            )
        }

        return try {
            json.decodeFromJsonElement(fileSerializer, root)
        } catch (e: SerializationException) {
            throw BackupException(MSG_CORRUPT, e)
        } catch (e: IllegalArgumentException) {
            throw BackupException(MSG_CORRUPT, e)
        }
    }

    /** Content overview of [file]. */
    fun summaryOf(file: BackupFile): BackupSummary = BackupSummary(
        exportedAtMillis = parseTimestamp(file.exportedAt),
        appVersion = file.appVersion?.takeIf { it.isNotBlank() },
        foods = file.foods.size,
        recipes = file.recipes.size,
        diaryEntries = file.diary.size,
        measurements = file.measurements.size,
        activityDays = file.activity.size,
    )

    /** "2026-11-05T14:05:00+01:00" (seconds precision, local offset). */
    fun timestamp(now: OffsetDateTime = OffsetDateTime.now()): String =
        DateTimeFormatter.ISO_OFFSET_DATE_TIME.format(now.truncatedTo(ChronoUnit.SECONDS))

    /** Epoch millis of an ISO timestamp, or null. */
    fun parseTimestamp(value: String?): Long? {
        if (value.isNullOrBlank()) return null
        return try {
            OffsetDateTime.parse(value).toInstant().toEpochMilli()
        } catch (e: Exception) {
            try {
                Instant.parse(value).toEpochMilli()
            } catch (e2: Exception) {
                null
            }
        }
    }

    private const val BOM: String = "﻿"
}
