/** Mini-Raster für die Regelkarten. pattern: 9 Zeichen – x = Kreuz, c = Katze, . = leer */
export function miniGrid(pattern) {
  let s = '<svg viewBox="0 0 33 33" aria-hidden="true" class="mini-grid">';
  for (let i = 0; i < 9; i++) {
    const x = (i % 3) * 11;
    const y = Math.floor(i / 3) * 11;
    const ch = pattern[i];
    s += `<rect x="${x + 0.5}" y="${y + 0.5}" width="10" height="10" rx="1.6" fill="${ch === 'x' ? '#f6e9df' : '#dcc4ad'}" stroke="${ch === 'x' ? '#b2775f' : 'none'}" stroke-width="1"/>`;
    if (ch === 'x') s += `<path d="M${x + 3} ${y + 3}l5 5m0-5-5 5" stroke="#9c5b45" stroke-width="1.6" stroke-linecap="round"/>`;
    if (ch === 'c') {
      s += `<g transform="translate(${x + 1.3} ${y + 1.6}) scale(.21)"><path d="M6 15 5 2.5l10.5 7.2q4.5-1.4 9 0L35 2.5 34 15q3 4.5 2.4 9.6C35.3 32 28.5 34.5 20 34.5S4.7 32 3.6 24.6Q3 19.5 6 15z" fill="#2c2b31"/><path d="M20 14c-3 0-4 6-6 9-4 2-4 8 2 9.5h8c6-1.5 6-7.5 2-9.5-2-3-3-9-6-9z" fill="#fff"/><circle cx="13" cy="19" r="2.6" fill="#fff"/><circle cx="27" cy="19" r="2.6" fill="#fff"/></g>`;
    }
  }
  return `${s}</svg>`;
}
